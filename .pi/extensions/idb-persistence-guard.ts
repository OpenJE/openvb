/**
 * IDB Persistence Guard (OpenVB harness) - with AUTOSAVE
 *
 * Why this exists: the headless IDA MCP servers do NOT auto-save. Renames,
 * comments and type edits live only in the server process until an explicit
 * save_database(...). A devenv/ImHex restart reloads the on-disk `.i64` and
 * silently rolls back every uncommitted write - this erased batch-2/3 (223
 * renames) on 2026-10-21.
 *
 * Layers of defense:
 *  1. AUTOSAVE: after the last IDA-mutating call goes quiet for IDLE_MS, the
 *     guard itself calls `py_eval -> ida_loader.save_database(...)` over the
 *     server's streamable-HTTP MCP endpoint (same port the agent uses; the
 *     server serializes requests, so this cannot race the agent's calls),
 *     proves disk moved via mtime, and appends a census line to
 *     artifacts/idb-guard-census.log. On session end / settle it force-saves
 *     any dirty server too. Crash-safety beats nudge-safety.
 *  2. NUDGE: if autosave did not happen or could not be proven (server down,
 *     unexpected tool schema, wrong path), the agent is NOT allowed to settle
 *     quietly - a followUp names the server, the write count, the autosave
 *     failure reason, and the exact manual save+census steps. Bounded: 2
 *     actionable nudges + one final warning per wave.
 *  3. MANUAL: /idb_guard status | save [server] | ack <server>.
 *
 * Config (all optional env overrides; defaults match devenv/environment/openvb.nix):
 *   OPENVB_IDA_ORIG_MCP_PORT / OPENVB_IDA_REIMPL_MCP_PORT   (8745 / 8746)
 *   OPENVB_IDA_GUARD_TOOL          MCP tool that executes IDAPython (py_eval)
 *   OPENVB_IDA_GUARD_TOOL_ARG      its code argument name   (code)
 *   IDB paths: $OPENVB_ORIG_IDB / $OPENVB_REIMPL_IDB with documented fallbacks.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";

interface ServerState {
	key: string;
	name: string;
	label: string;
	idbEnv: string;
	idbDefault: string;
	portEnv: string;
	defaultPort: string;
	dirty: boolean;
	writeCount: number;
	lastWriteMs: number;
	nudges: number;
	finalWarned: boolean;
	idleTimer: ReturnType<typeof setTimeout> | null;
	lastAutosave: string; // '' | 'ok' | reason
}

const IDLE_MS = 5000;
const MAX_NUDGES = 2;
const READ_ONLY_TOOL =
	/^(decompile|disasm|disassemble|xrefs?|get_|read_|list|search|find|query|census|dump|addr|names?|types?|imports?|exports?|strings?|funcs?|functions?|pseudocode|analyze|segment|header|meta|dbg_(status|regs|mem|threads?|breakpoints_list)|ida_version|server_(status|info))/i;
const SAVE_TOKEN = /save_database|saveIDB|ida_loader\.save_database/i;
const WRITE_IN_PYEV =
	/rename|set_(name|type|color|comment|args|dword|word|byte)|update_?comment|add_?comment|del_?(items|comm|name)|patch_?(bytes|mem)|PutByte|PutDword|MakeCode|MakeData|OpOne|OpAny|apply_(type|idb)|idc\.|ida_(api|kern|loader|utils)\.[a-z_]*\.(set|add|del|update|patch)|start_?process|continue_?process|load_?idb|switch_?(idb|base)/i;
const EXEC_TOOL = /py_eval|py_exec|run_?(script|code)|exec|eval/i;

const SAVE_SCRIPT = [
	"import json, ida_loader, idautils, idc",
	"_p = ida_loader.get_path(ida_loader.PATH_TYPE_IDB)",
	"_ok = bool(ida_loader.save_database(_p, 0))",
	"_all = list(idautils.Functions())",
	"_named = sum(1 for ea in _all if not idc.get_func_name(ea).startswith('sub_'))",
	"print(json.dumps({'saved': _ok, 'functions': len(_all), 'named': _named}))",
].join("\n");

// Runs INSIDE the IDA server's python: writes the full named-entries ledger
// directly to disk (no stdout limits). Only real analysis names are kept -
// IDA's autogenerated sub_/loc_/dword_... placeholders would bury the signal.
// NOTE: py_eval execs with SEPARATE globals/locals dicts - comprehensions
// cannot see code-defined locals; plain loops only.
const ledgerDumpScript = (outPath: string): string => {
	return [
		"import json, os, time, idautils",
		`_out = r"${outPath}"`,
		"os.makedirs(os.path.dirname(_out), exist_ok=True)",
		"_skip = ('sub_','loc_','unk_','off_','asc_','byte_','word_','dword_','qword_','flt_','dbl_','align_','noret_','seg_','doubleword_')",
		"_names = []",
		"for ea, nm in sorted(idautils.Names()):",
		"    if not nm.startswith(_skip):",
		"        _names.append((hex(ea), nm))",
		"_meta = {'ts': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()), 'entries': len(_names), 'note': 'EA->name ledger; recovery source after restart/rollback'}",
		"_f = open(_out, 'w')",
		"_f.write(json.dumps(_meta) + chr(10))",
		"for ea, nm in _names:",
		"    _f.write(json.dumps({'ea': ea, 'name': nm}) + chr(10))",
		"_f.close()",
		"print(json.dumps({'ledger': _out, 'entries': len(_names)}))",
	].join("\n");
};

function pruneLedgers(dirPath: string, keep = 20): void {
	try {
		const files = fs.readdirSync(dirPath).filter((f) => f.endsWith(".jsonl")).sort();
		for (const old of files.slice(0, Math.max(0, files.length - keep))) fs.unlinkSync(path.join(dirPath, old));
	} catch {
		/* pruning best effort */
	}
}

function servers(): ServerState[] {
	return [
		{
			key: "mcp__ida_original_f3__",
			name: "ida_original_f3",
			label: "ORIGINAL F3 IDB",
			idbEnv: "OPENVB_ORIG_IDB",
			idbDefault: "artifacts/F3.exe.i64",
			portEnv: "OPENVB_IDA_ORIG_MCP_PORT",
			defaultPort: "8745",
			dirty: false,
			writeCount: 0,
			lastWriteMs: 0,
			nudges: 0,
			finalWarned: false,
			idleTimer: null,
			lastAutosave: "",
		},
		{
			key: "mcp__ida_reimplementation_openvb__",
			name: "ida_reimplementation_openvb",
			label: "REIMPLEMENTATION IDB (ephemeral)",
			idbEnv: "OPENVB_REIMPL_IDB",
			idbDefault: "build/F3.exe.i64",
			portEnv: "OPENVB_IDA_REIMPL_MCP_PORT",
			defaultPort: "8746",
			dirty: false,
			writeCount: 0,
			lastWriteMs: 0,
			nudges: 0,
			finalWarned: false,
			idleTimer: null,
			lastAutosave: "",
		},
	];
}

export default function (pi: ExtensionAPI) {
	let state = servers();
	// Anchor relative paths to the SESSION workspace (ctx.cwd), not the pi
	// process cwd, which can be the user's home when launched elsewhere.
	let baseCwd = process.cwd();
	const R = (x: string): string => path.resolve(baseCwd, x);

	const idbPath = (s: ServerState): string =>
		process.env[s.idbEnv] ? R(process.env[s.idbEnv]!) : R(s.idbDefault);

	const mtimeOf = (s: ServerState): number | undefined => {
		try {
			return fs.statSync(idbPath(s)).mtimeMs;
		} catch {
			return undefined;
		}
	};

	const endpoint = (s: ServerState): string =>
		`http://127.0.0.1:${process.env[s.portEnv] || s.defaultPort}/mcp?ext=dbg`;

	const ledgerDir = (): string => R(process.env.OPENVB_LEDGER_DIR || "artifacts/ledgers");

	const dumpLedger = async (s: ServerState): Promise<string> => {
		const stamp = new Date().toISOString().replace(/[:.]/g, "-");
		const out = path.join(ledgerDir(), `${s.name}-${stamp}.jsonl`);
		try {
			const r = (await mcpCall(s, ledgerDumpScript(out))) as { isError?: boolean; text?: string };
			let pyErr = !!r.isError;
			try {
				const wrap = JSON.parse(String(r.text));
				if (typeof wrap.stderr === "string" && wrap.stderr.trim().length > 0) pyErr = true;
			} catch {
				/* unwrapped output: trust isError */
			}
			if (pyErr) return `ledger FAILED: ${String(r.text).slice(0, 200)}`;
			pruneLedgerAndLog(out);
			return `ledger ok: ${out}`;
		} catch (err) {
			return `ledger FAILED: ${err instanceof Error ? err.message : String(err)}`;
		}
	};

	const pruneLedgerAndLog = (written: string): void => {
		pruneLedgers(path.dirname(written));
	};

	const toolName = (): string => process.env.OPENVB_IDA_GUARD_TOOL || "py_eval";
	const toolArg = (): string => process.env.OPENVB_IDA_GUARD_TOOL_ARG || "code";

	/** Prove disk state and log a census line. Returns true when disk >= last write. */
	const diskProof = (s: ServerState, census?: Record<string, unknown>): boolean => {
		const m = mtimeOf(s);
		const proven = m !== undefined && m >= s.lastWriteMs;
		try {
			const line = JSON.stringify({
				ts: new Date().toISOString(),
				server: s.name,
				disk: idbPath(s),
				mtime: m ? new Date(m).toISOString() : null,
				proven,
				...(census ? { census } : {}),
			});
			fs.appendFileSync(path.join(path.dirname(idbPath(s)), "idb-guard-census.log"), line + "\n");
		} catch {
			/* census log is best effort; proof still returned */
		}
		return proven;
	};

	// Minimal streamable-HTTP MCP client: initialize -> initialized -> tools/call.
	const mcpCall = async (s: ServerState, script: string): Promise<Record<string, unknown>> => {
		const url = endpoint(s);
		const headers = { "content-type": "application/json", accept: "application/json, text/event-stream" };
		const init = await fetch(url, {
			method: "POST",
			headers,
			body: JSON.stringify({
				jsonrpc: "2.0",
				id: 1,
				method: "initialize",
				params: {
					protocolVersion: "2025-03-26",
					capabilities: {},
					clientInfo: { name: "idb-persistence-guard", version: "2.0.0" },
				},
			}),
			signal: AbortSignal.timeout(8000),
		});
		if (!init.ok) throw new Error(`initialize HTTP ${init.status}`);
		const sessionId = init.headers.get("mcp-session-id");
		const rpcHeaders: Record<string, string> = { ...headers, ...(sessionId ? { "mcp-session-id": sessionId } : {}) };
		await fetch(url, {
			method: "POST",
			headers: rpcHeaders,
			body: JSON.stringify({ jsonrpc: "2.0", method: "notifications/initialized" }),
			signal: AbortSignal.timeout(8000),
		});
		const res = await fetch(url, {
			method: "POST",
			headers: rpcHeaders,
			body: JSON.stringify({
				jsonrpc: "2.0",
				id: 2,
				method: "tools/call",
				params: { name: toolName(), arguments: { [toolArg()]: script } },
			}),
			signal: AbortSignal.timeout(30000),
		});
		if (!res.ok) throw new Error(`tools/call HTTP ${res.status}`);
		const text = await res.text();
		// SSE framing: keep only the last data: payload line, if present.
		const dataLine = text.split("\n").filter((l) => l.startsWith("data:")).pop();
		const payload = JSON.parse((dataLine ? dataLine.slice(5) : text).trim());
		if (payload.error) throw new Error(`rpc ${payload.error.code}: ${payload.error.message}`);
		const result = payload.result ?? {};
		const contentText = (result.content || [])
			.filter((c: { type?: string }) => c.type === "text")
			.map((c: { text?: string }) => c.text || "")
			.join("");
		return { isError: !!result.isError, text: contentText };
	};

	const autosave = async (s: ServerState): Promise<void> => {
		try {
			const out = await mcpCall(s, SAVE_SCRIPT);
			if (out.isError) throw new Error(`tool error: ${String(out.text).slice(0, 160)}`);
			let census: Record<string, unknown> | undefined;
			try {
				const outer = JSON.parse(String(out.text).trim());
				const inner = typeof outer.stdout === "string" ? outer.stdout : String(out.text);
				census = JSON.parse(String(inner).trim().split("\n").pop() || "");
			} catch {
				try {
					census = JSON.parse(String(out.text).trim().split("\n").pop() || "");
				} catch {
					/* census optional */
				}
			}
			if (!diskProof(s, census)) throw new Error("save did not move disk mtime");
			s.dirty = false;
			const led = await dumpLedger(s);
			s.lastAutosave = led.startsWith("ledger ok") ? "ok" : led;
			if (!led.startsWith("ledger ok")) s.lastAutosave = "ok (save) but " + led;
			s.nudges = 0;
			s.finalWarned = false;
		} catch (err) {
			s.lastAutosave = err instanceof Error ? err.message : String(err);
		}
	};

	const armIdle = (s: ServerState): void => {
		if (s.idleTimer) clearTimeout(s.idleTimer);
		s.idleTimer = setTimeout(() => {
			s.idleTimer = null;
			if (s.dirty) void autosave(s);
		}, IDLE_MS);
	};

	const nudgeText = (s: ServerState): string => {
		const m = mtimeOf(s);
		return [
			`[idb-guard] ${s.label}: ${s.writeCount} unsaved write(s), last at ${new Date(s.lastWriteMs).toISOString()}.`,
			s.lastAutosave && s.lastAutosave !== "ok"
				? `Autosave attempt failed: ${s.lastAutosave} (endpoint ${endpoint(s)}, tool ${toolName()}).`
				: "",
			m === undefined
				? `The .i64 on disk is not visible (${idbPath(s)}); locate it before claiming the wave is safe.`
				: `Disk mtime ${new Date(m).toISOString()} is older than the last IDB write - uncommitted renames/comments/types WILL be lost on the next restart (see the batch-2/3 erasure).`,
			`Required now, per the standing rule: (1) py_eval -> save_database on ${s.name}; (2) re-check the .i64 mtime moved; (3) dump a census (known EAs/names) proving disk state == live state; keep the ledger committed. Do not end the turn until all three are done.`,
		]
			.filter(Boolean)
			.join(" ");
	};

	pi.on("session_start", (_e: unknown, ctx: { cwd: string }) => {
		baseCwd = ctx.cwd;
		for (const s of state) {
			if (s.idleTimer) clearTimeout(s.idleTimer);
			s.idleTimer = null;
			s.dirty = false;
			s.writeCount = 0;
			s.lastWriteMs = 0;
			s.nudges = 0;
			s.finalWarned = false;
			s.lastAutosave = "";
		}
	});

	pi.on("tool_call", (event) => {
		// The `ida` wrapper tool routes through the same two servers - its writes
		// must arm autosave and its save action counts as a save, exactly like
		// direct mcp__ida_* calls.
		if (event.toolName === "ida") {
			const input = event.input as Record<string, unknown>;
			const s = state.find((x) => (input.target === "original" ? x.key === "mcp__ida_original_f3__" : x.key === "mcp__ida_reimplementation_openvb__"));
			if (!s) return;
			const action = String(input.action ?? "");
			if (action === "save") {
				s.dirty = false;
				s.nudges = 0;
				s.finalWarned = false;
				return;
			}
			if (action !== "call" && action !== "batch") return; // health/list_tools are inert
			const opList: { tool: string; args?: Record<string, unknown> }[] =
				action === "call"
					? [{ tool: String(input.tool ?? ""), args: input.args as Record<string, unknown> | undefined }]
					: ((input.ops ?? []) as { tool?: string; args?: Record<string, unknown> }[]).map((o) => ({
							tool: String(o.tool ?? ""),
							args: o.args,
						}));
			let mutates = false;
			let saves = false;
			for (const op of opList) {
				const code = String(op.args?.code ?? op.args?.script ?? "");
				if (SAVE_TOKEN.test(code)) {
					saves = true;
					continue;
				}
				if (EXEC_TOOL.test(op.tool)) {
					if (WRITE_IN_PYEV.test(code)) mutates = true; // py_eval judged by content only
				} else if (!READ_ONLY_TOOL.test(op.tool)) {
					mutates = true;
				}
			}
			if (saves && !mutates) {
				s.dirty = false;
				s.nudges = 0;
				s.finalWarned = false;
				return;
			}
			if (!mutates) return;
			s.dirty = true;
			s.writeCount += 1;
			s.lastWriteMs = Date.now();
			armIdle(s);
			return;
		}
		const s = state.find((x) => event.toolName.startsWith(x.key));
		if (!s) return;
		const shortName = event.toolName.slice(s.key.length);
		const input = event.input as Record<string, unknown>;
		const codeText =
			typeof input.code === "string"
				? input.code
				: typeof input.script === "string"
					? input.script
					: "";

		if (codeText && SAVE_TOKEN.test(codeText)) {
			s.dirty = false;
			s.nudges = 0;
			s.finalWarned = false;
			return;
		}
		const mutates = EXEC_TOOL.test(shortName) ? WRITE_IN_PYEV.test(codeText) : !READ_ONLY_TOOL.test(shortName);
		if (!mutates) return;
		s.dirty = true;
		s.writeCount += 1;
		s.lastWriteMs = Date.now();
		armIdle(s); // autosave once the wave goes quiet
	});

	pi.on("agent_before_settle", async () => {
		for (const s of state) {
			if (s.idleTimer) {
				clearTimeout(s.idleTimer);
				s.idleTimer = null;
			}
			if (s.dirty) await autosave(s); // final safety net before settling
			if (s.dirty) {
				// autosave failed: escalate to the bounded nudge path
				if (s.nudges < MAX_NUDGES) {
					s.nudges += 1;
					s.dirty = false; // any new write re-arms it
					pi.sendUserMessage(nudgeText(s), { deliverAs: "followUp" });
				} else if (!s.finalWarned) {
					s.finalWarned = true;
					s.dirty = false;
					pi.sendUserMessage(
						`[idb-guard] ${s.label} STILL unsaved after ${MAX_NUDGES} reminders and autosave failure (${s.lastAutosave}). Restarting IDA/devenv now erases this wave. /idb_guard ack ${s.name} only after independently verifying disk state.`,
						{ deliverAs: "followUp" },
					);
				}
			}
		}
	});

	pi.registerCommand("idb_guard", {
		description: "IDB persistence: status | save [server] | ack <server>",
		handler: async (args, ctx) => {
			const parts = (args ?? "").trim().split(/\s+/);
			const cmd = parts[0] || "status";
			const pick = (name?: string) => state.find((s) => !name || s.name === name || s.name.includes(name));
			if (cmd === "ack") {
				const hit = pick(parts[1]);
				if (hit) {
					hit.dirty = false;
					ctx.ui.notify(`idb-guard: cleared ${hit.label} after manual verification`, "info");
				} else ctx.ui.notify("usage: /idb_guard ack <server-name>", "warning");
				return;
			}
			if (cmd === "save") {
				for (const s of state.filter((x) => (parts[1] ? x === pick(parts[1]) : true))) {
					ctx.ui.notify(`idb-guard: autosaving ${s.name}...`, "info");
					await autosave(s);
					ctx.ui.notify(
						`idb-guard: ${s.name} autosave -> ${s.lastAutosave}`,
						s.lastAutosave === "ok" ? "info" : "error",
					);
				}
				return;
			}
			const lines = state.map((s) => {
				const m = mtimeOf(s);
				const status = s.dirty
					? `DIRTY (${s.writeCount} write(s), last ${new Date(s.lastWriteMs).toISOString()})`
					: "clean";
				return `${s.name} [${status}] disk=${m ? new Date(m).toISOString() : "missing"} autosave=${s.lastAutosave || "-"} nudges=${s.nudges}`;
			});
			ctx.ui.notify(lines.join("\n"), "info");
		},
	});
}
